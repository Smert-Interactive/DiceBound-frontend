// UUID нужны только для новых записей в памяти; генератор работает и по HTTP в локальной сети.
let sequence = 1;

// Общий счётчик не даёт новым выдачам и копиям получить один ID до перезагрузки приложения.
export function createMockId() {
  return `f0000000-1000-4000-8000-${(sequence++).toString(16).padStart(12, "0")}`;
}
